#!/usr/bin/env node
'use strict';

const http = require('http');
const net = require('net');
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const DEFAULT_PORT = 5500;

// api-gateway и realtime-gateway (stub-python) слушают 8222 и 8090
// (см. backend/gateways/apiGateway/config/app/config.json и
//  backend/gateways/realtimeGateway/stub-python/app/config.py).
const API_TARGET = new URL(process.env.API_TARGET || 'http://localhost:8222');
const WS_TARGET = new URL(process.env.WS_TARGET || 'http://localhost:8090');
const WS_PATH = process.env.WS_PATH || '/ws';

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.wav': 'audio/wav',
  '.mp3': 'audio/mpeg',
  '.txt': 'text/plain; charset=utf-8',
  '.map': 'application/json; charset=utf-8',
};

const NO_CACHE = {
  'Cache-Control': 'no-store, no-cache, must-revalidate',
  Pragma: 'no-cache',
  Expires: '0',
};

function parsePort() {
  const arg = process.argv.slice(2).find((a) => !a.startsWith('-'));
  const value = arg !== undefined ? arg : process.env.PORT;
  if (value === undefined) return DEFAULT_PORT;
  const port = Number(value);
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    console.error(`Некорректный порт: ${value}`);
    process.exit(1);
  }
  return port;
}

function send(res, status, type, body, method) {
  res.writeHead(status, { 'Content-Type': type, 'Content-Length': Buffer.byteLength(body), ...NO_CACHE });
  res.end(method === 'HEAD' ? undefined : body);
}

function handler(req, res) {
  const method = req.method === 'HEAD' ? 'HEAD' : 'GET';
  let pathname;
  try {
    pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  } catch {
    pathname = '/';
  }

  // Прокси API, чтобы фронтенд и гейтвей были на одном origin (без CORS).
  if (pathname === '/api' || pathname.startsWith('/api/')) {
    return proxyHttp(req, res);
  }

  const resolved = path.resolve(ROOT, '.' + pathname);
  if (resolved !== ROOT && !resolved.startsWith(ROOT + path.sep)) {
    log(req, 403);
    return send(res, 403, 'text/plain; charset=utf-8', '403 Forbidden', method);
  }

  // Включаем Google-вход: client id берём из окружения (GOOGLE_CLIENT_ID из .env).
  if (pathname === '/js/oauth.js') {
    const clientId = process.env.GOOGLE_CLIENT_ID || '';
    const body =
      '/** @generated by frontend/server.js — GOOGLE_CLIENT_ID из окружения. */\n' +
      'window.DURAK_CONFIG = Object.assign({}, window.DURAK_CONFIG || {}, {\n' +
      `    googleClientId: ${JSON.stringify(clientId)},\n` +
      '});\n';
    return send(res, 200, MIME['.js'], body, method);
  }

  fs.stat(resolved, (err, stat) => {
    let file = resolved;
    if (!err && stat.isDirectory()) file = path.join(resolved, 'index.html');

    fs.readFile(file, (readErr, data) => {
      if (readErr) {
        log(req, 404);
        return send(res, 404, 'text/plain; charset=utf-8', '404 Not Found', method);
      }
      const type = MIME[path.extname(file).toLowerCase()] || 'application/octet-stream';
      res.writeHead(200, { 'Content-Type': type, 'Content-Length': data.length, ...NO_CACHE });
      res.end(method === 'HEAD' ? undefined : data);
      log(req, 200);
    });
  });
}

function proxyHttp(req, res) {
  const headers = { ...req.headers, host: API_TARGET.host };
  const port = API_TARGET.port || (API_TARGET.protocol === 'https:' ? 443 : 80);

  const proxyReq = http.request({
    hostname: API_TARGET.hostname,
    port,
    method: req.method,
    path: req.url,
    headers,
  }, proxyRes => {
    res.writeHead(proxyRes.statusCode || 502, proxyRes.headers);
    proxyRes.pipe(res);
    proxyRes.on('end', () => log(req, proxyRes.statusCode || 502));
  });

  proxyReq.on('error', err => {
    if (!res.headersSent) {
      res.writeHead(502, {
        'Content-Type': 'application/json; charset=utf-8',
        ...NO_CACHE,
      });
    }
    res.end(JSON.stringify({
      code: 'BAD_GATEWAY',
      message: 'api-gateway недоступен: ' + err.message,
    }));
    log(req, 502);
  });

  req.pipe(proxyReq);
}

function proxyUpgrade(req, socket, head) {
  let pathname;
  try {
    pathname = new URL(req.url, 'http://localhost').pathname;
  } catch {
    pathname = '';
  }
  if (pathname !== WS_PATH) {
    socket.destroy();
    return;
  }

  const port = WS_TARGET.port || (WS_TARGET.protocol === 'https:' ? 443 : 80);
  const upstream = net.connect(port, WS_TARGET.hostname, () => {
    const headers = { ...req.headers, host: WS_TARGET.host };
    const lines = [`${req.method} ${req.url} HTTP/1.1`];
    for (const [name, value] of Object.entries(headers)) {
      if (Array.isArray(value)) lines.push(`${name}: ${value.join(', ')}`);
      else if (value !== undefined) lines.push(`${name}: ${value}`);
    }
    upstream.write(lines.join('\r\n') + '\r\n\r\n');
    if (head && head.length) upstream.write(head);
    upstream.pipe(socket);
    socket.pipe(upstream);
  });

  upstream.on('error', () => socket.destroy());
  socket.on('error', () => upstream.destroy());
}

function log(req, status) {
  process.stdout.write(`${req.socket.remoteAddress} - "${req.method} ${req.url}" ${status}\n`);
}

function main() {
  if (!fs.existsSync(path.join(ROOT, 'index.html'))) {
    console.error(`Не найден index.html в ${ROOT}`);
    process.exit(1);
  }

  const port = parsePort();
  const server = http.createServer(handler);
  server.on('upgrade', proxyUpgrade);

  server.on('error', (err) => {
    console.error(err.code === 'EADDRINUSE' ? `Порт ${port} уже занят` : err.message);
    process.exit(1);
  });

  server.listen(port, () => {
    console.log('Дурак — веб-фронтенд');
    console.log(`  Раздаётся папка: ${ROOT}`);
    console.log(`  API proxy:       /api/* -> ${API_TARGET.origin}`);
    console.log(`  WS proxy:        ${WS_PATH}  -> ${WS_TARGET.origin}${WS_PATH}`);
    console.log(`  Открой в браузере: http://localhost:${port}/`);
    console.log('  Остановить: Ctrl+C');
  });

  process.on('SIGINT', () => {
    console.log('\nОстановлено.');
    server.close(() => process.exit(0));
  });
}

main();
